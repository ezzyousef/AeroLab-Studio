"""Write the two SYNTHETIC demo files for the viscoelastic measurements.

No relaxation or creep data came with the papers, so the demo files for those two
measurements are generated here from textbook models with a fixed random seed. Each file
says so in its first lines; neither is a measurement and neither should be cited.

    py -3 build_assets/make_synthetic_samples.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[1] / "aerolab" / "resources" / "samples"


def main() -> None:
    rng = np.random.default_rng(20261115)

    # Standard linear solid, 5 % strain step: E_inf = 2 MPa, E1 = 3 MPa, tau = 40 s
    t = np.concatenate([np.linspace(0.5, 20, 40), np.linspace(21, 600, 120)])
    stress = 0.05 * (2.0 + 3.0 * np.exp(-t / 40.0))
    stress *= 1 + rng.normal(0, 0.004, t.size)
    lines = ["# SYNTHETIC demonstration data - not a measurement.",
             "# Standard linear solid, 5 % strain step: E_inf = 2 MPa, E1 = 3 MPa, tau = 40 s; 0.4 % noise.",
             "# Generated by build_assets/make_synthetic_samples.py (seed 20261115).",
             "Time (s),Stress (MPa)"]
    lines += [f"{a:.2f},{b:.5f}" for a, b in zip(t, stress)]
    (OUT / "relaxation_synthetic.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Burgers creep under 0.5 MPa: J0 = 0.2, J1 = 0.1 1/MPa, tau = 120 s, 1/eta = 2e-5 1/(MPa s)
    t = np.linspace(0, 1800, 181)
    strain = 100 * 0.5 * (0.2 + 0.1 * (1 - np.exp(-t / 120.0)) + 2e-5 * t)
    strain += rng.normal(0, 0.03, t.size)
    lines = ["# SYNTHETIC demonstration data - not a measurement.",
             "# Burgers creep at 0.5 MPa: J0 = 0.2 1/MPa, J1 = 0.1 1/MPa, tau = 120 s, 1/eta = 2e-5 1/(MPa s); "
             "0.03 % strain noise.",
             "# Generated by build_assets/make_synthetic_samples.py (seed 20261115).",
             "Time (s),Strain (%)"]
    lines += [f"{a:.1f},{b:.4f}" for a, b in zip(t, strain)]
    (OUT / "creep_synthetic.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
